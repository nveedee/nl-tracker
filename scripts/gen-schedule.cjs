function toDate(dm) {
  const [d, m] = dm.split('.').map(Number)
  const year = m >= 9 ? 2026 : 2027
  return `${year}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`
}

const seen = {}
const games = rows.map(([home, away, time, dm]) => {
  const date = toDate(dm)
  const key = `${date}_${home}_${away}`
  seen[key] = (seen[key] || 0) + 1
  const suffix = seen[key] > 1 ? `_${seen[key]}` : ''
  return {
    id: `game_${date}_${home}_${away}${suffix}`,
    date,
    time,
    homeTeamId: `team_${home}`,
    awayTeamId: `team_${away}`,
    status: 'scheduled',
    homeGoals: null,
    awayGoals: null,
    decision: null,
    playerStats: [],
  }
})

const seedPath = path.join(__dirname, '..', 'server', 'data', 'seed.json')
const seed = JSON.parse(fs.readFileSync(seedPath, 'utf-8'))
seed.games = games
fs.writeFileSync(seedPath, JSON.stringify(seed, null, 2))
